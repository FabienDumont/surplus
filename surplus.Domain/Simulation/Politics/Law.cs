namespace Surplus.Domain.Simulation.Politics;

/// <summary>
/// A statute outlawing a relation of production. Laws do not create classes —
/// the base does that — but by forbidding a relation they force everyone
/// standing in it to become something else, and what they become is settled by
/// who still holds the land and the workshops.
/// </summary>
public enum Law
{
  AbolitionOfSlavery,
  SerfEmancipation,
  EnclosureActs,
  LandReform,
  NationalisationOfIndustry,
  AbolitionOfWageLabour
}
